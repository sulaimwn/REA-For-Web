// Trusted operator tool only. Uses normal admission/queue processing, never
// imports demo JSON or writes cache metadata directly.
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { lstat } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { MAX_UPLOAD_BYTES, SIGNED_UPLOAD_SECONDS, UPLOAD_TTL_SECONDS, validateUpload, uploadKind, type JobStatus } from './contracts.js';
import type { UploadControl } from './server.js';
import { LocalStore, uploadKey } from './storage.js';

type Control = Pick<UploadControl, 'config' | 'create' | 'complete' | 'status'>;
export type PreanalysisOptions = {
  sourcePath: string;
  expectedSha256?: string;
  signal?: AbortSignal;
  onStatus?: (status: JobStatus) => void;
};
export class PreanalysisError extends Error {
  constructor(public readonly stage: string) {
    super(`Pre-analysis failed at ${stage}. Check the file and private service configuration.`);
    this.name = 'PreanalysisError';
  }
}

async function interruptible<T>(work: () => Promise<T>, signal: AbortSignal): Promise<T> {
  signal.throwIfAborted();
  let abort: (() => void) | undefined;
  try {
    return await Promise.race([work(), new Promise<never>((_, reject) => {
      abort = () => reject(signal.reason);
      signal.addEventListener('abort', abort, { once: true });
      if (signal.aborted) abort();
    })]);
  } finally { if (abort) signal.removeEventListener('abort', abort); }
}

export async function preanalyzeFile(control: Control, options: PreanalysisOptions) {
  const path = resolve(options.sourcePath);
  let stage = 'file validation';
  let cleanupKey: string | undefined;
  let completionAttempted = false;
  const signal = AbortSignal.any([
    ...(options.signal ? [options.signal] : []),
    AbortSignal.timeout(UPLOAD_TTL_SECONDS * 1000),
  ]);
  try {
    signal.throwIfAborted();
    const info = await lstat(path);
    if (!info.isFile() || info.isSymbolicLink() || info.size < 1 || info.size > MAX_UPLOAD_BYTES)
      throw new Error('Invalid source file.');
    if (options.expectedSha256 !== undefined && !/^[a-f0-9]{64}$/u.test(options.expectedSha256))
      throw new Error('Invalid expected digest.');
    const name = basename(path);
    // Reject unsupported names/hostile paths before reading or creating a ticket.
    validateUpload({ name, bytes: info.size, sha256: '0'.repeat(64) });
    stage = 'file hashing';
    const hash = createHash('sha256');
    let bytes = 0;
    for await (const chunk of createReadStream(path, { signal })) {
      bytes += chunk.length;
      if (bytes > info.size) throw new Error('File changed during hashing.');
      hash.update(chunk);
    }
    const sha256 = hash.digest('hex');
    if (bytes !== info.size) throw new Error('File changed during hashing.');
    stage = 'release digest verification';
    if (options.expectedSha256 !== undefined && sha256 !== options.expectedSha256)
      throw new Error('Release digest mismatch.');
    const request = validateUpload({ name, bytes, sha256 });
    stage = 'upload admission';
    const ticket = await interruptible(() => control.create(request), signal);
    cleanupKey = uploadKey(ticket.jobId, uploadKind(name)!);
    signal.throwIfAborted();
    stage = 'file upload';
    if (control.config.store instanceof LocalStore) {
      // Local mode requires no web server, but keeps its signed-byte validation.
      const signed = new URL(ticket.uploadUrl);
      await control.config.store.receive(ticket.jobId, request,
        Number(signed.searchParams.get('expires')), signed.searchParams.get('signature')!,
        createReadStream(path, { signal }));
    } else {
      // R2's signed URL was generated by this trusted control/configuration.
      // Never accept an upload URL or job token from command-line arguments.
      const body = createReadStream(path, { signal });
      try {
        const response = await fetch(ticket.uploadUrl, {
          method: 'PUT', headers: { ...ticket.headers, 'Content-Length': String(bytes) },
          body, duplex: 'half',
          signal: AbortSignal.any([signal, AbortSignal.timeout(SIGNED_UPLOAD_SECONDS * 1000)]),
          redirect: 'error',
        });
        await response.body?.cancel();
        if (!response.ok) throw new Error('Object upload failed.');
      } finally { body.destroy(); }
    }
    signal.throwIfAborted();
    stage = 'queue completion';
    // A lost completion response might still have enqueued the job. From here,
    // only the worker/expiry sweep owns raw cleanup; never delete an active input.
    completionAttempted = true;
    let status = await interruptible(() => control.complete(ticket.jobId, ticket.jobToken), signal);
    stage = 'queued analysis';
    for (;;) {
      options.onStatus?.(status);
      if (status.status === 'succeeded') {
        const projectId = status.projectId;
        if (typeof projectId !== 'string' || !/^[a-f0-9]{64}$/u.test(projectId) || typeof status.cacheHit !== 'boolean') throw new Error('Invalid result receipt.');
        return { sha256, kind: uploadKind(name)!, projectId, cacheHit: status.cacheHit };
      }
      if (status.status === 'failed') throw new Error('Analysis failed.');
      await delay(1000, undefined, { signal });
      status = await interruptible(() => control.status(ticket.jobId, ticket.jobToken), signal);
    }
  } catch {
    if (cleanupKey && !completionAttempted) {
      try { await control.config.store.delete(cleanupKey); }
      catch { throw new PreanalysisError('unsubmitted upload cleanup'); }
    }
    if (signal.aborted) throw new PreanalysisError('waiting interrupted (queued jobs continue normally)');
    throw new PreanalysisError(stage);
  }
}
